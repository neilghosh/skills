# ─── Audio Helpers ────────────────────────────────────────────────────────────
def load_wav_stereo_48k(wav_path, target_samples=None):
    if not wav_path or not os.path.exists(wav_path):
        return None
    data, sr = sf.read(wav_path, dtype='float32')
    if data.ndim == 1:
        data = np.column_stack([data, data])
    elif data.shape[1] > 2:
        data = data[:, :2]
    if sr != SR:
        data = resample_poly(data, SR // 1000, sr // 1000, axis=0).astype(np.float32)
    if target_samples is not None:
        if len(data) < target_samples:
            pad = np.zeros((target_samples - len(data), 2), dtype=np.float32)
            data = np.vstack([data, pad])
        elif len(data) > target_samples:
            data = data[:target_samples]
    return data.astype(np.float32)


def find_real_ambient_npy_path(seg):
    """Locate the real voice-suppressed ambient NPY (`amb_<clip>_*.npy`) for a segment."""
    clip_file = seg['file']
    mp4_dir = os.path.dirname(seg.get('mp4', ''))
    if mp4_dir:
        cands = glob.glob(os.path.join(mp4_dir, 'ambient_cache', f'amb_{clip_file}_*.npy'))
        if cands:
            return cands[0]
    for d in ALL_AMB_DIRS:
        cands = glob.glob(os.path.join(d, f'amb_{clip_file}_*.npy'))
        if cands:
            return cands[0]
    return None


def load_real_segment_ambient(seg, target_samples, fallback_arr=None):
    """
    Loads the segment's real voice-suppressed surrounding audio (car, water, wind, nature)
    without ever replacing quiet natural scenes with synthetic noise.
    """
    npy_path = find_real_ambient_npy_path(seg)
    arr = None
    if npy_path and os.path.exists(npy_path):
        raw = np.load(npy_path).astype(np.float32)
        rms = float(np.sqrt(np.mean(raw ** 2)))
        if rms > 1e-4:
            arr = raw

    # If this clip was a silent GoPro TimeWarp hyperlapse (rms == 0), inherit from chapter neighbor
    if arr is None and fallback_arr is not None:
        arr = fallback_arr.copy()

    if arr is None:
        return np.zeros((target_samples, 2), dtype=np.float32)

    if len(arr) < target_samples:
        arr = np.pad(arr, ((0, target_samples - len(arr)), (0, 0)), mode='reflect')
    else:
        arr = arr[:target_samples].copy()

    # Preserve natural dynamics of car, water, and wind while keeping comfortable broadcast levels
    rms = float(np.sqrt(np.mean(arr ** 2)) + 1e-9)
    if rms > 0.065:
        # Gently tame excessive highway wind buffeting while retaining full engine/road character
        arr = arr * (0.060 / rms)
    elif rms < 0.020:
        # Gently lift quiet stream/forest/bird ambience so water & breeze are clearly audible
        gain = min(3.0, 0.028 / rms)
        arr = arr * gain

    # 30ms micro-fade at clip boundaries to prevent click artifacts between cuts
    fade_n = min(int(0.03 * SR), len(arr) // 4)
    if fade_n > 0:
        arr[:fade_n] *= np.linspace(0.0, 1.0, fade_n, dtype=np.float32)[:, None]
        arr[-fade_n:] *= np.linspace(1.0, 0.0, fade_n, dtype=np.float32)[:, None]

    return arr.astype(np.float32)


# ─── Synthesizers ─────────────────────────────────────────────────────────────
def synthesize_edge_tts(text, voice, rate, out_wav):
    if os.path.exists(out_wav) and os.path.getsize(out_wav) > 1000:
        return True
    with tempfile.NamedTemporaryFile(suffix='.mp3', delete=False) as tmp:
        tmp_mp3 = tmp.name
    try:
        cmd = [EDGE_TTS_BIN, '--voice', voice, '--text', text, '--write-media', tmp_mp3]
        if rate:
            cmd.append(f'--rate={rate}')
        res = subprocess.run(cmd, capture_output=True, timeout=45)
        if res.returncode != 0 or not os.path.exists(tmp_mp3) or os.path.getsize(tmp_mp3) < 400:
            return False
        subprocess.run([
            '/opt/homebrew/bin/ffmpeg', '-y', '-v', 'error',
            '-i', tmp_mp3, '-ar', '48000', '-ac', '2', out_wav
        ], check=True)
        return True
    except Exception as e:
        print(f"    [Edge-TTS ERR] {voice} '{text[:30]}': {e}")
        return False
    finally:
        if os.path.exists(tmp_mp3):
            os.remove(tmp_mp3)


def batch_synthesize_odia(timeline, scripts, tts_dir):
    """Batch synthesize all 58 Odia lines using f5_batch_synth.py in ONE warm MLX session."""
    batch_items = []
    wav_paths = {}
    for g_idx, group in enumerate(timeline):
        text = scripts[g_idx].get('odia', '')
        if not text:
            wav_paths[g_idx] = None
            continue
        h = hashlib.sha1(f"odia:{text}".encode('utf-8')).hexdigest()[:12]
        wav_path = os.path.join(tts_dir, f"narr_odia_{g_idx:03d}_{h}.wav")
        wav_paths[g_idx] = wav_path
        if not os.path.exists(wav_path) or os.path.getsize(wav_path) < 1000:
            batch_items.append({
                'text': text,
                'output': wav_path,
                'voice': 'odia'
            })

    if batch_items:
        print(f"  [Odia IndicF5] Synthesizing {len(batch_items)} items in warm MLX batch...")
        batch_json = os.path.join(WORK_OUT, 'odia_batch_synth.json')
        with open(batch_json, 'w') as f:
            json.dump(batch_items, f, indent=2)
        subprocess.run([
            f"{VOICE_DEV_DIR}/.venv/bin/python",
            BATCH_SYNTH_BIN,
            "--batch-json", batch_json,
            "--voice", "odia",
            "--steps", "8",
            "-q", "0"
        ], check=True)
    else:
        print("  [Odia IndicF5] All 58 segments already cached.")

    return wav_paths


# ─── Group-Level Track Assembly (Real Surrounding Ambience + Clean Speech) ────
def build_track(v_tag, voice, rate, lang, label, engine, timeline, segments, scripts, music_master, tts_dir, force_rebuild=True):
    out_m4a = os.path.join(AUDIO_TRACKS, f'track_{v_tag}_scratch.m4a')
    if not force_rebuild and os.path.exists(out_m4a) and os.path.getsize(out_m4a) > 20_000_000:
        print(f"\n[Phase 3] Using cached track: {os.path.basename(out_m4a)} ({os.path.getsize(out_m4a)/(1024*1024):.1f} MB)")
        return out_m4a

    print(f"\n[Phase 3] Building track with Real Voice-Suppressed Surrounding Audio: {label} -> {os.path.basename(out_m4a)}")

    if engine == 'indic_batch':
        narr_wavs = batch_synthesize_odia(timeline, scripts, tts_dir)
    else:
        print(f"  Verifying 58 TTS lines for {voice}...")
        narr_wavs = {}
        def synth_one(g_idx):
            text = scripts[g_idx].get(v_tag, '')
            if not text:
                return g_idx, None
            h = hashlib.sha1(f"{v_tag}:{text}".encode('utf-8')).hexdigest()[:12]
            wav_path = os.path.join(tts_dir, f"narr_{v_tag}_{g_idx:03d}_{h}.wav")
            ok = synthesize_edge_tts(text, voice, rate, wav_path)
            return g_idx, (wav_path if ok else None)

        with concurrent.futures.ThreadPoolExecutor(max_workers=8) as ex:
            futs = [ex.submit(synth_one, i) for i in range(len(timeline))]
            for fut in concurrent.futures.as_completed(futs):
                idx, p = fut.result()
                narr_wavs[idx] = p

    # Stream audio directly to ffmpeg to encode m4a
    proc = subprocess.Popen([
        '/opt/homebrew/bin/ffmpeg', '-y', '-v', 'error',
        '-f', 'f32le', '-ar', '48000', '-ac', '2', '-i', '-',
        '-c:a', 'aac', '-b:a', '160k', out_m4a
    ], stdin=subprocess.PIPE)

    # Group segments by chapter (group_idx)
    group_segs = defaultdict(list)
    for seg in segments:
        group_segs[seg['group_idx']].append(seg)

    sample_cursor = 0
    music_len = len(music_master)
    last_valid_amb = None

    # Process group-by-group: real car/water/wind ambience + subtle music + clean speech
    for g_idx in range(len(timeline)):
        segs_in_group = group_segs[g_idx]
        group_samples = sum(max(1, int(round(s['dur'] * SR))) for s in segs_in_group)

        # Find a valid ambient reference in this chapter for any silent TimeWarp clip
        chap_ref_amb = last_valid_amb
        for s in segs_in_group:
            p = find_real_ambient_npy_path(s)
            if p and os.path.exists(p):
                raw = np.load(p).astype(np.float32)
                if float(np.sqrt(np.mean(raw ** 2))) > 1e-4:
                    chap_ref_amb = raw
                    last_valid_amb = raw
                    break

        # 1. Slice subtle cinematic music bed (-30 dBFS underlay so real surroundings shine)
        m_slice = np.zeros((group_samples, 2), dtype=np.float32)
        avail = max(0, min(group_samples, music_len - sample_cursor))
        if avail > 0:
            m_slice[:avail] = music_master[sample_cursor:sample_cursor + avail] * 0.42
        sample_cursor += group_samples

        # 2. Concatenate REAL voice-suppressed surrounding sound (car, water, wind, birds)
        amb_chunks = []
        for s in segs_in_group:
            s_dur = s['dur']
            s_samp = max(1, int(round(s_dur * SR)))
            s_amb = load_real_segment_ambient(s, s_samp, fallback_arr=chap_ref_amb)
            amb_chunks.append(s_amb)

        group_amb = np.concatenate(amb_chunks, axis=0) if amb_chunks else np.zeros((group_samples, 2), dtype=np.float32)
        if len(group_amb) < group_samples:
            pad = np.zeros((group_samples - len(group_amb), 2), dtype=np.float32)
            group_amb = np.vstack([group_amb, pad])
        elif len(group_amb) > group_samples:
            group_amb = group_amb[:group_samples]

        # 3. Narration & Dynamic Ducking
        wav = narr_wavs.get(g_idx)
        narr_arr = load_wav_stereo_48k(wav)

        if narr_arr is not None and len(narr_arr) > 0:
            inset = int(0.25 * SR)  # 0.25s pause before speech starts
            narr_len = min(len(narr_arr), group_samples - inset)

            # Duck real ambient to 45% during speech so voice is crystal clear,
            # then restore to 100% so car/water/wind are vivid on B-rolls!
            group_amb[inset:inset + narr_len] *= 0.45
            m_slice[inset:inset + narr_len] *= 0.45

            # Smooth 0.5s un-duck ramp back to full natural ambience
            ramp_len = min(int(SR * 0.5), group_samples - (inset + narr_len))
            if ramp_len > 0:
                ramp = np.linspace(0.45, 1.0, ramp_len)[:, None]
                group_amb[inset + narr_len:inset + narr_len + ramp_len] *= ramp
                m_slice[inset + narr_len:inset + narr_len + ramp_len] *= ramp

            # Mix: real voice-suppressed surrounding sound + subtle music + narration
            final_group = group_amb + m_slice
            final_group[inset:inset + narr_len] += narr_arr[:narr_len]
        else:
            # Non-speech B-roll: 100% real surrounding ambience + gentle music
            final_group = group_amb + m_slice

        # 4. Peak Limiter
        peak = float(np.max(np.abs(final_group)) + 1e-9)
        if peak > 0.95:
            final_group = final_group * (0.92 / peak)

        proc.stdin.write(final_group.astype(np.float32).tobytes())

    proc.stdin.close()
    proc.wait()
    print(f"  Finished {os.path.basename(out_m4a)} ({os.path.getsize(out_m4a)/(1024*1024):.1f} MB)")
    return out_m4a


# ─── Main Execution Pipeline ──────────────────────────────────────────────────
def main():
    print("=" * 70)
    print("HYDERABAD -> KERALA EXPEDITION: 5-LANGUAGE BROADCAST BUILD")
    print("Real Voice-Suppressed Surrounding Audio (Car, Water, Wind) + Subtle Score")
    print("=" * 70)

    os.makedirs(AUDIO_TRACKS, exist_ok=True)
    tts_dir = os.path.join(WORK_OUT, 'tts_scratch_cache')
    os.makedirs(tts_dir, exist_ok=True)

    timeline = json.load(open(os.path.join(WORK_OUT, 'equal_timeline_final.json')))
    segments = json.load(open(os.path.join(WORK_OUT, 'segments_info.json')))
    scripts  = load_scripts()

    print(f"Loaded {len(timeline)} chapters, {len(segments)} video segments.")

    # 1. Load continuous 26-minute cinematic music bed
    print(f"Loading master cinematic music bed from {MUSIC_BED_NPY}...")
    music_master = np.load(MUSIC_BED_NPY).astype(np.float32)
    print(f"  Loaded {len(music_master)} samples ({len(music_master)/SR:.2f}s).")

    # 2. Build all 5 audio tracks
    track_m4as = []
    for v_tag, voice, rate, lang, label, engine in VOICE_SPECS:
        m4a = build_track(v_tag, voice, rate, lang, label, engine, timeline, segments, scripts, music_master, tts_dir, force_rebuild=True)
        track_m4as.append(m4a)

    # 3. Validate all tracks
    print("\n[Phase 4] Validating audio tracks...")
    for m4a in track_m4as:
        p = subprocess.run([
            '/opt/homebrew/bin/ffprobe', '-v', 'error',
            '-show_entries', 'stream=codec_type', '-of', 'default=noprint_wrappers=1:nokey=1',
            m4a
        ], capture_output=True, text=True)
        if 'audio' not in p.stdout:
            raise RuntimeError(f"Corrupt audio track: {m4a}")
    print("  All 5 audio tracks validated successfully.")

    # 4. Final Multiplexing into FINAL_MP4 with strict YouTube duration matching
    vid_dur = float(subprocess.check_output([
        '/opt/homebrew/bin/ffprobe', '-v', 'error',
        '-select_streams', 'v:0',
        '-show_entries', 'stream=duration', '-of', 'default=noprint_wrappers=1:nokey=1',
        FINAL_MP4
    ]).decode().strip())
    print(f"\n[Phase 5] Multiplexing video ({vid_dur:.3f}s) + 5 audio tracks (strict YouTube alignment) -> {FINAL_MP4}")

    temp_mux = os.path.join(VIDEO_DIR, 'work', 'temp_mux_multiaudio.mp4')
    cmd = ['/opt/homebrew/bin/ffmpeg', '-y', '-v', 'error', '-i', FINAL_MP4]
    for m4a in track_m4as:
        cmd += ['-i', m4a]

    cmd += ['-map', '0:v:0']
    for i, (v_tag, voice, rate, lang, label, engine) in enumerate(VOICE_SPECS):
        cmd += [
            '-map', f'{i+1}:a:0',
            f'-metadata:s:a:{i}', f'language={lang}',
            f'-metadata:s:a:{i}', f'title={label}',
            f'-metadata:s:a:{i}', f'handler_name={label}',
            f'-disposition:a:{i}', 'default' if i == 0 else '0'
        ]

    cmd += ['-t', f'{vid_dur:.3f}', '-shortest', '-c:v', 'copy', '-c:a', 'copy', temp_mux]
    subprocess.run(cmd, check=True)

    # Atomically replace final mp4
    os.replace(temp_mux, FINAL_MP4)

    print("\n" + "=" * 70)
    print(f"BUILD COMPLETE: {FINAL_MP4}")
    dur_out = subprocess.check_output([
        '/opt/homebrew/bin/ffprobe', '-v', 'error',
        '-show_entries', 'format=duration', '-of', 'default=noprint_wrappers=1:nokey=1',
        FINAL_MP4
    ]).decode().strip()
    print(f"Final MP4 Duration: {float(dur_out)/60:.2f} minutes ({dur_out}s)")
    print(f"Size: {os.path.getsize(FINAL_MP4)/(1024*1024*1024):.2f} GB")
    print("=" * 70)


if __name__ == '__main__':
    main()
